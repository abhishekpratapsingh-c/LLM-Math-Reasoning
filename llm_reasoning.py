"""
llm_reasoning.py
----------------
Phase 3: Automatic Error Detection in LLM Reasoning.
Objective 18: LLM Mathematical Problem Solver.

Accepts mathematical problems and generates step-by-step reasoning using
existing LLM providers (Gemini free-tier, Groq).
Returns the complete raw textual reasoning response without parsing or filtering.
Zero paid APIs. Completely modular.
"""

import os
import sys
from typing import Optional, Any

# Ensure project root is in sys.path
sys.path.append(os.path.dirname(os.path.abspath(__file__)))

from main import get_llm_client, call_llm


REASONING_PROMPT_TEMPLATE = (
    "Solve the following mathematical problem step by step.\n\n"
    "Requirements:\n"
    "1. Show your complete mathematical reasoning.\n"
    "2. Present your work as clearly numbered steps (e.g., Step 1:, Step 2:, ...).\n"
    "3. State your equations and calculations explicitly in each step.\n"
    "4. Clearly identify the final numerical answer at the end in the format: 'Final Answer: <value>'.\n\n"
    "Problem:\n"
    "{problem}"
)

SUPPORTED_PROVIDERS = ("gemini", "groq")


def generate_reasoning(
    problem: str,
    provider: str = "gemini",
    client: Optional[Any] = None,
    model_name: Optional[str] = None,
) -> str:
    """
    Submits a mathematical problem to the specified LLM provider and retrieves
    its complete step-by-step reasoning.

    Parameters
    ----------
    problem : str
        The mathematical word problem or question to solve.
    provider : str, default 'gemini'
        The LLM provider to query ('gemini' or 'groq').
    client : Any, optional
        An optional pre-initialized LLM client instance (for testing/dependency injection).
    model_name : str, optional
        An optional model override (for testing/dependency injection).

    Returns
    -------
    str
        The complete, unparsed, raw textual response generated by the LLM.

    Raises
    ------
    ValueError
        If the problem string is empty, whitespace, or invalid, or if the provider is unsupported.
    RuntimeError
        If an API error, rate limit, or network failure occurs during client initialization or inference.
    """
    # 1. Validate problem input
    if problem is None or not isinstance(problem, str) or not problem.strip():
        raise ValueError("Problem input cannot be empty, whitespace, or non-string.")

    # 2. Validate provider selection
    if not isinstance(provider, str) or provider.strip().lower() not in SUPPORTED_PROVIDERS:
        raise ValueError(
            f"Unsupported provider '{provider}'. Supported providers: {list(SUPPORTED_PROVIDERS)}."
        )

    provider_norm = provider.strip().lower()
    cleaned_problem = problem.strip()
    prompt = REASONING_PROMPT_TEMPLATE.format(problem=cleaned_problem)

    # 3. Initialize client if not injected
    if client is None or model_name is None:
        try:
            init_client, init_model = get_llm_client(provider_norm)
            active_client = client if client is not None else init_client
            active_model = model_name if model_name is not None else init_model
        except ValueError:
            # Propagate configuration errors (e.g. missing API keys or invalid provider)
            raise
        except Exception as e:
            raise RuntimeError(f"Failed to initialize client for provider '{provider_norm}': {e}") from e
    else:
        active_client = client
        active_model = model_name

    # 4. Execute LLM inference with graceful error handling
    try:
        raw_response = call_llm(active_client, provider_norm, active_model, prompt)
        if raw_response is None or not str(raw_response).strip():
            raise RuntimeError(
                f"LLM provider '{provider_norm}' (model '{active_model}') returned an empty response."
            )
        return str(raw_response)
    except RuntimeError:
        # Propagate handled runtime errors (e.g. rate limit quota exhaustion from call_llm)
        raise
    except Exception as e:
        err_str = str(e)
        if "429" in err_str or "RESOURCE_EXHAUSTED" in err_str or "rate_limit" in err_str.lower():
            raise RuntimeError(
                f"Rate limit exceeded while querying '{provider_norm}' ({active_model}): {e}"
            ) from e
        raise RuntimeError(
            f"Inference error with LLM provider '{provider_norm}' ({active_model}): {e}"
        ) from e


if __name__ == "__main__":
    demo_problem = (
        "A shopkeeper buys 3 notebooks for ₹40 each and 2 pens for ₹15 each. What is the total cost?"
    )
    problem_to_solve = sys.argv[1] if len(sys.argv) > 1 else demo_problem
    provider_to_use = sys.argv[2] if len(sys.argv) > 2 else "gemini"

    print("=" * 75)
    print("PHASE 3, OBJECTIVE 18: LLM MATHEMATICAL REASONING DEMONSTRATION")
    print("=" * 75)
    print(f"Problem:  {problem_to_solve}")
    print(f"Provider: {provider_to_use}")
    print("-" * 75)
    print("Querying LLM for step-by-step mathematical reasoning...\n")

    try:
        reasoning_output = generate_reasoning(problem_to_solve, provider=provider_to_use)
        print("Complete Raw Reasoning Response:")
        print("-" * 75)
        print(reasoning_output)
        print("-" * 75)
        print("\nDemonstration completed successfully.")
    except Exception as err:
        print(f"Error during reasoning generation: {err}")
        sys.exit(1)
