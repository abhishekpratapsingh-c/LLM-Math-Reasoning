"""
step_extractor.py
-----------------
Phase 3: Automatic Error Detection in LLM Reasoning.
Objective 19: Extract Intermediate Mathematical Steps.

Extracts individual intermediate mathematical reasoning steps and the final answer
from the raw textual response generated by an LLM (e.g. from llm_reasoning.py).
Preserves the complete original mathematical text and equations of each step without
altering formatting, symbols, or calculations.
Supports Markdown headers, bold headings, and various numbering schemes.
"""

from dataclasses import dataclass, field
import os
import re
import sys
from typing import List, Optional, Dict, Any

# Ensure project root is in sys.path
sys.path.append(os.path.dirname(os.path.abspath(__file__)))


# Regex for explicit "Step N" headers (supports Markdown headers, bolding, colons, dashes, etc.)
# Matches: "**Step 1: Heading**", "Step 1:", "### Step 1 - Title", "**Step 1**", etc.
STEP_KEYWORD_PATTERN = re.compile(
    r"(?m)^\s*(?:#{1,6}\s*)?(?:\*\*|\*|__)?\s*Step\s+(\d+)\s*(?::|\.|\-|\))?(?:\*\*|\*|__)?\s*(?::|\.|\-|\))?\s*(.*?)(?:\*\*|\*|__)?\s*$",
    re.IGNORECASE,
)

# Regex for alternative numbered list items (e.g. "1. Heading", "1) Heading", "**1.** Heading")
# Used as fallback when no explicit "Step N" markers exist in the response.
ALT_NUMBERED_PATTERN = re.compile(
    r"(?m)^\s*(?:#{1,6}\s*)?(?:\*\*|\*|__)?\s*(\d+)\s*(?:\.|\)|\:|\-)(?:\*\*|\*|__)?\s*(?::|\.|\-|\))?\s*(.*?)(?:\*\*|\*|__)?\s*$",
    re.IGNORECASE,
)

# Regex patterns for detecting and isolating the final answer section/line
FINAL_ANSWER_PATTERNS = [
    # Explicit Final Answer header or statement
    # e.g., "Final Answer: 150", "**Final Answer:** 150", "The final answer is: 150"
    re.compile(
        r"(?i)(?:^|\n)\s*(?:#{1,6}\s*)?(?:\*\*|\*|__)?\s*(?:The\s+)?(?:Final\s+Answer|Answer|Result)\s*(?:is\s*)?(?:[:\.\-]\s*)?(?:\*\*|\*|__)?\s*(?:is\s*)?[:\.\-]?\s*(.*?)(?:\*\*|\*|__)?\s*$",
        re.MULTILINE,
    ),
    # GSM8K delimiter: "#### 150"
    re.compile(r"(?m)^\s*####\s*(.*?)\s*$"),
]


@dataclass
class ReasoningStep:
    """Represents a single extracted intermediate mathematical reasoning step."""
    step_number: int                 # Parsed integer step number (e.g., 1, 2, 3)
    step_header: str                 # The original header line (e.g., "**Step 1: Calculate...**")
    text: str                        # Full raw text of the step including header and equations
    step_content: str                # Body text of the step excluding the header line

    def to_dict(self) -> Dict[str, Any]:
        return {
            "step_number": self.step_number,
            "step_header": self.step_header,
            "text": self.text,
            "step_content": self.step_content,
        }

    def __str__(self) -> str:
        return self.text


@dataclass
class ExtractedReasoning:
    """Structured container holding all extracted steps and separated final answer."""
    raw_response: str
    steps: List[ReasoningStep] = field(default_factory=list)
    final_answer: Optional[str] = None
    final_answer_raw: Optional[str] = None
    status: str = "success"          # 'success', 'no_steps_found', 'empty_response', 'malformed'
    explanation: str = ""
    is_sequential: bool = True
    missing_step_numbers: List[int] = field(default_factory=list)

    def to_dict(self) -> Dict[str, Any]:
        return {
            "raw_response": self.raw_response,
            "steps": [s.to_dict() for s in self.steps],
            "final_answer": self.final_answer,
            "final_answer_raw": self.final_answer_raw,
            "status": self.status,
            "explanation": self.explanation,
            "is_sequential": self.is_sequential,
            "missing_step_numbers": self.missing_step_numbers,
        }


def _extract_final_answer(text: str) -> tuple[Optional[str], Optional[str], Optional[int]]:
    """
    Finds the last occurrence of a final answer marker in the text.
    Returns: (cleaned_answer_value, raw_answer_line, match_start_position)
    """
    best_match = None
    for pattern in FINAL_ANSWER_PATTERNS:
        for match in pattern.finditer(text):
            if best_match is None or match.start() > best_match.start():
                best_match = match

    if best_match:
        raw_line = best_match.group(0).strip()
        val = best_match.group(1).strip()
        # Clean enclosing markdown bold/italics and trailing periods
        val_clean = re.sub(r"^[\*\_\`\s]+|[\*\_\`\s]+$", "", val).rstrip(".")
        return val_clean, raw_line, best_match.start()

    return None, None, None


def extract_reasoning_steps(raw_response: str) -> ExtractedReasoning:
    """
    Extracts each intermediate reasoning step and the final answer from an LLM's raw response.

    Parameters
    ----------
    raw_response : str
        The complete, raw textual output produced by the LLM.

    Returns
    -------
    ExtractedReasoning
        Dataclass containing:
        - raw_response: original complete text untouched
        - steps: list of ReasoningStep instances in chronological order
        - final_answer: extracted cleaned final answer string (or None)
        - final_answer_raw: extracted raw final answer line (or None)
        - status: 'success', 'no_steps_found', 'empty_response', or 'malformed'
        - explanation: descriptive summary of extraction findings
        - is_sequential: bool indicating if step numbers are sequential 1..N
        - missing_step_numbers: list of missing integers if numbering is discontinuous
    """
    # 1. Handle empty / whitespace / non-string input gracefully
    if not isinstance(raw_response, str) or not raw_response.strip():
        return ExtractedReasoning(
            raw_response=str(raw_response) if raw_response is not None else "",
            steps=[],
            final_answer=None,
            final_answer_raw=None,
            status="empty_response",
            explanation="Raw response is empty, whitespace, or non-string.",
            is_sequential=False,
            missing_step_numbers=[],
        )

    # 2. Identify and separate the final answer
    final_answer, final_answer_raw, fa_start = _extract_final_answer(raw_response)
    if fa_start is not None:
        reasoning_body = raw_response[:fa_start]
    else:
        reasoning_body = raw_response

    # 3. Detect step markers (preferring explicit 'Step N' markers over plain numbered lists)
    matches = list(STEP_KEYWORD_PATTERN.finditer(reasoning_body))
    using_keyword_pattern = True

    if not matches:
        # Fall back to alternative numbered markers (1., 2., 3. or 1), 2), 3))
        matches = list(ALT_NUMBERED_PATTERN.finditer(reasoning_body))
        using_keyword_pattern = False

    # 4. Handle cases where no steps were identified
    if not matches:
        return ExtractedReasoning(
            raw_response=raw_response,
            steps=[],
            final_answer=final_answer,
            final_answer_raw=final_answer_raw,
            status="no_steps_found",
            explanation="No numbered reasoning steps detected in response.",
            is_sequential=False,
            missing_step_numbers=[],
        )

    # 5. Extract step text slices between consecutive markers
    steps: List[ReasoningStep] = []
    for i, match in enumerate(matches):
        step_num = int(match.group(1))
        start_idx = match.start()
        end_idx = matches[i + 1].start() if i + 1 < len(matches) else len(reasoning_body)

        full_step_text = reasoning_body[start_idx:end_idx].strip()
        lines = full_step_text.splitlines()

        if lines:
            header_line = lines[0].strip()
            # If the step text has multiple lines, body is lines[1:]
            if len(lines) > 1:
                content = "\n".join(lines[1:]).strip()
            else:
                # Single-line step: content is the portion following the step number/marker
                inline_content = match.group(2).strip()
                content = inline_content if inline_content else header_line
        else:
            header_line = full_step_text
            content = full_step_text

        steps.append(
            ReasoningStep(
                step_number=step_num,
                step_header=header_line,
                text=full_step_text,
                step_content=content,
            )
        )

    # 6. Check numbering continuity and handle malformed numbering gracefully
    numbers = [s.step_number for s in steps]
    is_sequential = True
    missing_numbers: List[int] = []

    if numbers:
        expected_range = list(range(numbers[0], numbers[0] + len(numbers)))
        if numbers != expected_range or numbers[0] != 1:
            is_sequential = False
            # Detect any skipped intermediate numbers in the span [min..max]
            full_span = set(range(min(numbers), max(numbers) + 1))
            missing_numbers = sorted(list(full_span - set(numbers)))

    if is_sequential:
        explanation = f"Successfully extracted {len(steps)} sequential reasoning steps."
        status = "success"
    else:
        status = "malformed"
        if missing_numbers:
            explanation = (
                f"Extracted {len(steps)} steps with discontinuous numbering. "
                f"Missing step numbers: {missing_numbers}. (Steps not silently invented)."
            )
        else:
            explanation = (
                f"Extracted {len(steps)} steps with non-standard numbering: {numbers}."
            )

    return ExtractedReasoning(
        raw_response=raw_response,
        steps=steps,
        final_answer=final_answer,
        final_answer_raw=final_answer_raw,
        status=status,
        explanation=explanation,
        is_sequential=is_sequential,
        missing_step_numbers=missing_numbers,
    )


