"""
reasoning_feedback.py
---------------------
Phase 3: Automatic Error Detection in LLM Reasoning.
Objective 24: Pass solver feedback to the LLM so it can explain why a
mathematical reasoning step is incorrect.

Combines:
1. Mathematical problem text.
2. Structured reasoning from Objective 20 (step_structurer.py).
3. SymPy-based assertion verification from Objective 21 (step_verifier.py).
4. Step transition verification from Objective 22 (step_transition_verifier.py).
5. Consolidated error reports from Objective 23 (reasoning_error_detector.py).

Core Capabilities:
- Identifies steps with definite errors, potential warnings, or unsupported expressions.
- Formulates focused, mathematically rigorous prompts containing:
    * Original problem statement.
    * Specific reasoning step text and mathematical expression.
    * Error category and severity.
    * Concrete mathematical evidence from the symbolic solver.
    * Relevant conditions or restrictions (e.g. division by zero, lost roots).
    * Clear task instruction requesting concise explanation and correction.
- Invokes free LLM providers (Gemini or Groq) using the existing client architecture.
- Optimizes API usage: When NO errors or warnings exist (e.g. completely sound reasoning),
  returns empty feedback immediately with ZERO external API calls.
- Strict evidence separation: Preserves deterministic solver findings completely separate
  from LLM-generated explanations; the LLM never overwrites or alters solver results.
- Returns structured, documented dataclasses (`StepFeedback`, `ReasoningFeedbackResult`).
"""

